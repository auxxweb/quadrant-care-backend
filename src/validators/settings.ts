import { z } from 'zod';

export const settingsSchema = z.object({
  companyName: z.string().min(2).optional(),
  appName: z.string().min(2).optional(),
  timezone: z.string().optional(),
  dateFormat: z.string().optional(),
  timeFormat: z.string().optional(),
  weekStartsOn: z.number().min(0).max(6).optional(),
  emailLoginEnabled: z.boolean().optional(),
  mobileLoginEnabled: z.boolean().optional(),
  passcodeLoginEnabled: z.boolean().optional(),
  passcodeLength: z.literal(5).optional(),
  requirePasscodeAfterFirstLogin: z.boolean().optional(),
  defaultBreakDuration: z.number().min(0).optional(),
  allowOvernightShifts: z.boolean().optional(),
  requireRemarks: z.boolean().optional(),
  requireInchargeName: z.boolean().optional(),
  requireAdminSignature: z.boolean().optional(),
  requireSuperAdminSignature: z.boolean().optional(),
  sessionDurationMinutes: z.number().min(5).optional(),
  maxLoginAttempts: z.number().min(3).optional(),
  lockoutDurationMinutes: z.number().min(1).optional(),
  passwordMinLength: z.number().min(8).optional(),
  passwordRequireUppercase: z.boolean().optional(),
  passwordRequireNumber: z.boolean().optional(),
  passwordRequireSpecial: z.boolean().optional(),
  staffSignupEnabled: z.boolean().optional(),
});
